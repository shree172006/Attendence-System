-- WARNING: this resets only the attendance application tables.
-- Run this file in Supabase SQL Editor before importing data.txt.

begin;
drop table if exists attendance_notifications cascade;
drop table if exists attendance cascade;
drop table if exists batches cascade;
drop table if exists student_guardians cascade;
drop table if exists students cascade;

create table students (
  id bigint generated by default as identity primary key,
  name text not null,
  class_name text not null,
  subjects text not null default '',
  guardian_phone text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table student_guardians (
  id bigint generated by default as identity primary key,
  student_id bigint not null references students(id) on delete cascade,
  guardian_name text not null default '',
  phone text not null,
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  unique(student_id, phone)
);

create table batches (
  id bigint generated by default as identity primary key,
  name text not null,
  class_name text not null,
  lecture_type text not null,
  start_time text not null default '',
  end_time text not null default '',
  created_at timestamptz not null default now()
);

create table attendance (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references batches(id) on delete cascade,
  student_id bigint not null references students(id) on delete cascade,
  attendance_date date not null,
  status text not null check (status in ('present', 'absent')),
  time_in text,
  time_out text,
  created_at timestamptz not null default now(),
  unique(batch_id, student_id, attendance_date)
);

create table attendance_notifications (
  id bigint generated by default as identity primary key,
  attendance_id bigint references attendance(id) on delete cascade,
  student_id bigint not null references students(id) on delete cascade,
  phone text not null,
  status text not null check (status in ('sent', 'failed', 'skipped')),
  message text not null,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index students_class_idx on students(class_name);
create index guardians_student_idx on student_guardians(student_id);
create index attendance_date_idx on attendance(attendance_date);
create index notifications_student_idx on attendance_notifications(student_id);

alter table students enable row level security;
alter table student_guardians enable row level security;
alter table batches enable row level security;
alter table attendance enable row level security;
alter table attendance_notifications enable row level security;

commit;

